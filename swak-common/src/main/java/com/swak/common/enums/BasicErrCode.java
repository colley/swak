package com.swak.common.enums;

/**
 * 基础全局错误码
 * 段位分配标准：
 * 0xx      - 系统基础
 * 4xx      - HTTP 协议标准映射（认证、请求格式）
 * 5xx      - 服务端内部异常及 RPC 调用异常
 * 6xx      - 安全策略与流量控制
 * 1000~10xx- 通用参数校验
 * 2000~20xx- 通用基础业务操作（CRUD兜底）
 *
 * @author colley.ma
 * @since 2022/9/9 16:24
 */
public enum BasicErrCode implements IResultCode {
	// ========================================== //
	//             0xx: 系统基础
	// ========================================== //
	/**
	 * 成功
	 */
	SUCCESS(0, "操作成功"),
	SWAK_ERROR(999, "系统繁忙，请稍后再试"),

	// ========================================== //
	//       4xx: HTTP协议标准映射 (客户端错误)
	// ========================================== //

	/**
	 * 请求参数格式错误（如：JSON 解析失败、非预期的 Content-Type）
	 */
	BAD_REQUEST(400, "请求参数格式错误"),

	/**
	 * 未认证（如：未携带 Token、Token 已过期）
	 */
	UNAUTHORIZED(401, "未登录或登录已过期，请先登录"),

	/**
	 * 无权限（如：已登录但角色/权限不足，无法访问该资源）
	 */
	FORBIDDEN(403, "无权限访问该资源"),

	/**
	/**
	 * 资源不存在（如：请求了不存在的接口 URL）
	 */
	NOT_FOUND(404, "请求的资源或接口不存在"),

	/**
	 * 请求方法不被允许（如：接口要求 POST，但客户端发送了 GET）
	 */
	METHOD_NOT_ALLOWED(405, "请求方法不被允许"),

	/**
	 * 请求体过大（如：上传文件超过了限制大小）
	 */
	PAYLOAD_TOO_LARGE(413, "请求数据量过大，请减小请求体大小"),

	/**
	 * 媒体类型不支持（如：接口要求 application/json，客户端发送了 XML）
	 */
	UNSUPPORTED_MEDIA_TYPE(415, "不支持的媒体类型"),


	// ========================================== //
	//     5xx: 服务端异常 (需触发运维告警)
	// ========================================== //
	/**
	 * 服务器内部错误（如：NPE、数组越界等不可预期的代码 Bug）
	 */
	INTERNAL_ERROR(500, "服务器内部异常，请稍后再试"),

	/**
	 * 网关错误（如：调用下游微服务/第三方接口时，下游服务挂掉返回 500）
	 */
	BAD_GATEWAY(502, "网关错误，依赖的下游服务异常"),

	/**
	 * 服务不可用（如：服务处于熔断降级状态，或正在发布中）
	 */
	SERVICE_UNAVAILABLE(503, "服务暂不可用，请稍后再试"),

	/**
	 * 网关超时（如：调用下游接口耗时过长导致超时）
	 */
	GATEWAY_TIMEOUT(504, "网关超时，下游服务响应过慢"),


	// ========================================== //
	//       6xx: 安全策略与流量控制
	// ========================================== //
	/**
	 * 签名校验失败（常用于开放 API 接口，参数签名不正确）
	 */
	SIGN_ERROR(600, "接口签名校验失败"),

	/**
	 * 重复提交（如：分布式锁拦截了表单重复提交）
	 */
	REPEAT_SUBMIT(601, "请勿重复提交，请稍后再试"),

	/**
	 * 业务级频率限制（如：单个用户每分钟只能发送1次短信）
	 */
	RATE_LIMITED(602, "操作过于频繁，已被限流，请稍后再试"),

	/**
	 * 系统授权过期（框架级商业授权限制）
	 */
	LICENSE_EXPIRED(605, "系统授权已失效，请联系管理员获取授权"),

	/**
	 * IP 黑名单拦截
	 */
	IP_FORBIDDEN(604, "当前访问IP已被列入黑名单"),

	// ========================================== //
	//       10xx: 通用参数校验 (基于 JSR 303 转换)
	// ========================================== //

	/**
	 * 参数不合法（通用兜底，具体场景应使用下面的细分码）
	 */
	PARAM_INVALID(1000, "参数不合法"),

	/**
	 * 必填参数缺失（对应 @NotNull, @NotBlank, @NotEmpty）
	 */
	PARAM_MISS(1001, "必填参数不能为空"),

	/**
	 * 参数类型错误（如：期望 Integer，传入了 String）
	 */
	PARAM_TYPE_ERROR(1002, "参数类型错误"),

	/**
	 * 参数格式错误（如：邮箱格式、手机号格式、时间格式不正确）
	 */
	PARAM_FORMAT_ERROR(1003, "参数格式不正确"),

	/**
	 * 参数超出允许范围（如：分页 pageSize=1000，最大只允许 100）
	 */
	PARAM_OUT_OF_RANGE(1004, "参数值超出允许范围"),

	/**
	 * 参数包含非法字符（如：检测到 SQL 注入、XSS 攻击特征）
	 */
	PARAM_ILLEGAL_CHAR(1005, "参数包含非法字符"),


	// ========================================== //
	//     20xx: 通用基础业务操作 (无专属模块时的兜底)
	// ========================================== //
	/**
	 * 通用业务异常（业务不满足前置条件时的兜底）
	 */
	BIZ_ERROR(2000, "业务处理异常，请稍后再试"),

	/**
	 * 新增/保存失败
	 */
	SAVE_FAILED(2001, "数据保存失败"),

	/**
	 * 修改/更新失败
	 */
	UPDATE_FAILED(2002, "数据更新失败"),

	/**
	 * 删除失败（如：存在外键关联无法删除）
	 */
	DELETE_FAILED(2003, "数据删除失败"),

	/**
	 * 查询失败
	 */
	QUERY_FAILED(2004, "数据查询失败"),
	/**
	 * 数据冲突（如：乐观锁版本号不一致导致更新失败）
	 */
	DATA_CONFLICT(2005, "数据已发生变更，请刷新后重试"),

	/**
	 * 数据状态异常（如：订单已取消，无法执行发货操作）
	 */
	DATA_STATUS_ERROR(2006, "当前数据状态不允许此操作"),

	/**
	 * 数据已存在（如：唯一索引冲突）
	 */
	DATA_EXISTED(2007, "数据已存在，请勿重复操作"),
	;

	private final Integer code;
	private final String msg;

	BasicErrCode(Integer code, String msg) {
		this.code = code;
		this.msg = msg;
	}

	@Override
	public Integer getCode() {
		return code;
	}

	@Override
	public String getMsg() {
		return msg;
	}
}
